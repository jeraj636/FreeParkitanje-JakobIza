DROP TABLE IF EXISTS REZERVACIJA;
DROP TABLE IF EXISTS USER_AVTO;
DROP TABLE IF EXISTS PARKING;
DROP TABLE IF EXISTS AVTO;
DROP TABLE IF EXISTS USER;
CREATE TABLE USER (
    id INT AUTO_INCREMENT PRIMARY KEY,
    ime VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(50) NOT NULL,
    geslo VARCHAR(255) NOT NULL
);

CREATE TABLE AVTO (
    id INT AUTO_INCREMENT PRIMARY KEY,
    registrska VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE PARKING (
    id INT AUTO_INCREMENT PRIMARY KEY,
    x INT NOT NULL,
    y INT NOT NULL,
    smer INT NOT NULL,
    UNIQUE (x, y, smer)
);

CREATE TABLE USER_AVTO (
    userID INT NOT NULL,
    avtoID INT NOT NULL,

    PRIMARY KEY (userID, avtoID),

    FOREIGN KEY (userID) REFERENCES USER(id)
        ON DELETE CASCADE,

    FOREIGN KEY (avtoID) REFERENCES AVTO(id)
        ON DELETE CASCADE
);

CREATE TABLE REZERVACIJA (
    id INT AUTO_INCREMENT PRIMARY KEY,
    zac DATETIME NOT NULL,
    kon DATETIME NOT NULL,
    parkingID INT NOT NULL,
    uporabnikID INT NOT NULL,
    avtoID INT NOT NULL,

    FOREIGN KEY (parkingID) REFERENCES PARKING(id),
    FOREIGN KEY (uporabnikID) REFERENCES USER(id),
    FOREIGN KEY (avtoID) REFERENCES AVTO(id),

    CHECK (kon > zac)
);